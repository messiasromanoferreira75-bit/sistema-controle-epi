
-- 1. SETOR
CREATE TABLE setor (
    id_setor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL UNIQUE
);

-- 2. FUNCIONARIO
CREATE TABLE funcionario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    matricula VARCHAR(120) NOT NULL UNIQUE,
    cargo VARCHAR(120),
    id_setor BIGINT NOT NULL,

    CONSTRAINT fk_funcionario_setor
        FOREIGN KEY (id_setor)
        REFERENCES setor(id_setor)
);

-- 3. EPI
CREATE TABLE epi (
    id_epi BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    tipo VARCHAR(120),
    estoque INTEGER NOT NULL DEFAULT 0,
    estoque_minimo INTEGER NOT NULL DEFAULT 0,

    CONSTRAINT chk_epi_estoque
        CHECK (estoque >= 0),

    CONSTRAINT chk_epi_estoque_minimo
        CHECK (estoque_minimo >= 0)
);

-- 4. ENTREGA
CREATE TABLE entrega (
    id_entrega BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_hora TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    id_funcionario BIGINT NOT NULL,
    id_responsavel BIGINT NOT NULL,
    assinatura_path VARCHAR(500),

    CONSTRAINT fk_entrega_funcionario
        FOREIGN KEY (id_funcionario)
        REFERENCES funcionario(id),

    CONSTRAINT fk_entrega_responsavel
        FOREIGN KEY (id_responsavel)
        REFERENCES funcionario(id)
);

-- 5. ITEM_ENTREGA
CREATE TABLE item_entrega (
    id_item BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quantidade INTEGER NOT NULL,
    id_entrega BIGINT NOT NULL,
    id_epi BIGINT NOT NULL,

    CONSTRAINT fk_item_entrega_entrega
        FOREIGN KEY (id_entrega)
        REFERENCES entrega(id_entrega),

    CONSTRAINT fk_item_entrega_epi
        FOREIGN KEY (id_epi)
        REFERENCES epi(id_epi),

    CONSTRAINT chk_item_entrega_quantidade
        CHECK (quantidade > 0),

    CONSTRAINT uq_item_entrega_epi
        UNIQUE (id_entrega, id_epi)
);