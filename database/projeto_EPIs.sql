-- Script reexecutável para o esquema público do Supabase.
CREATE TABLE IF NOT EXISTS setor (
    id_setor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS funcionario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    matricula VARCHAR(120) NOT NULL UNIQUE,
    cargo VARCHAR(120),
    id_setor BIGINT NOT NULL,
    CONSTRAINT fk_funcionario_setor FOREIGN KEY (id_setor) REFERENCES setor(id_setor)
);
CREATE TABLE IF NOT EXISTS epi (
    id_epi BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    tipo VARCHAR(120),
    ca VARCHAR(20),
    estoque INTEGER NOT NULL DEFAULT 0,
    estoque_minimo INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT chk_epi_estoque CHECK (estoque >= 0),
    CONSTRAINT chk_epi_estoque_minimo CHECK (estoque_minimo >= 0)
);
ALTER TABLE epi ADD COLUMN IF NOT EXISTS ca VARCHAR(20);
CREATE TABLE IF NOT EXISTS entrega (
    id_entrega BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_hora TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    id_funcionario BIGINT NOT NULL,
    id_responsavel BIGINT NOT NULL,
    assinatura_path VARCHAR(500),
    CONSTRAINT fk_entrega_funcionario FOREIGN KEY (id_funcionario) REFERENCES funcionario(id),
    CONSTRAINT fk_entrega_responsavel FOREIGN KEY (id_responsavel) REFERENCES funcionario(id)
);
CREATE TABLE IF NOT EXISTS item_entrega (
    id_item BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quantidade INTEGER NOT NULL,
    id_entrega BIGINT NOT NULL,
    id_epi BIGINT NOT NULL,
    CONSTRAINT fk_item_entrega_entrega FOREIGN KEY (id_entrega) REFERENCES entrega(id_entrega),
    CONSTRAINT fk_item_entrega_epi FOREIGN KEY (id_epi) REFERENCES epi(id_epi),
    CONSTRAINT chk_item_entrega_quantidade CHECK (quantidade > 0),
    CONSTRAINT uq_item_entrega_epi UNIQUE (id_entrega, id_epi)
);
CREATE INDEX IF NOT EXISTS idx_funcionario_id_setor ON funcionario(id_setor);
CREATE INDEX IF NOT EXISTS idx_entrega_id_funcionario ON entrega(id_funcionario);
CREATE INDEX IF NOT EXISTS idx_item_entrega_id_entrega ON item_entrega(id_entrega);
CREATE INDEX IF NOT EXISTS idx_item_entrega_id_epi ON item_entrega(id_epi);

CREATE OR REPLACE FUNCTION registrar_entrega(
    p_id_funcionario BIGINT,
    p_id_responsavel BIGINT,
    p_itens JSONB,
    p_assinatura_path TEXT DEFAULT NULL
)
RETURNS BIGINT LANGUAGE plpgsql AS $$
DECLARE
    v_id_entrega BIGINT;
    v_item JSONB;
    v_id_epi BIGINT;
    v_quantidade INTEGER;
BEGIN
    INSERT INTO entrega (id_funcionario, id_responsavel, assinatura_path)
    VALUES (p_id_funcionario, p_id_responsavel, p_assinatura_path)
    RETURNING id_entrega INTO v_id_entrega;

    IF p_itens IS NULL OR jsonb_typeof(p_itens) <> 'array' OR jsonb_array_length(p_itens) = 0 THEN
        RAISE EXCEPTION 'A entrega deve conter pelo menos um item' USING ERRCODE = '23514';
    END IF;

    FOR v_item IN SELECT value FROM jsonb_array_elements(p_itens)
    LOOP
        v_id_epi := (v_item->>'id_epi')::BIGINT;
        v_quantidade := (v_item->>'quantidade')::INTEGER;
        IF v_quantidade IS NULL OR v_quantidade <= 0 THEN
            RAISE EXCEPTION 'A quantidade deve ser maior que zero' USING ERRCODE = '23514';
        END IF;
        UPDATE epi SET estoque = estoque - v_quantidade WHERE id_epi = v_id_epi;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'EPI % não encontrado', v_id_epi USING ERRCODE = '23503';
        END IF;
        INSERT INTO item_entrega (id_entrega, id_epi, quantidade)
        VALUES (v_id_entrega, v_id_epi, v_quantidade);
    END LOOP;
    RETURN v_id_entrega;
END;
$$;

